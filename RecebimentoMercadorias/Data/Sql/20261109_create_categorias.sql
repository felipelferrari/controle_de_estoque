BEGIN;

CREATE TABLE IF NOT EXISTS categorias (
    id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL,
    descricao text,
    ativo boolean NOT NULL DEFAULT true,
    data_cadastro timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE categorias
    ADD COLUMN IF NOT EXISTS ativo boolean NOT NULL DEFAULT true;

ALTER TABLE categorias
    ADD COLUMN IF NOT EXISTS data_cadastro timestamp with time zone NOT NULL DEFAULT now();

INSERT INTO categorias (id_categoria, nome)
SELECT DISTINCT p.id_categoria, 'Categoria ' || p.id_categoria
FROM produtos p
WHERE p.id_categoria IS NOT NULL
ON CONFLICT (id_categoria) DO NOTHING;

SELECT setval(
    pg_get_serial_sequence('categorias', 'id_categoria'),
    GREATEST(COALESCE(MAX(id_categoria), 0), 1),
    COUNT(*) > 0
)
FROM categorias;

CREATE INDEX IF NOT EXISTS ix_produtos_id_categoria
    ON produtos (id_categoria);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_produtos_categorias_id_categoria'
          AND conrelid = 'produtos'::regclass
    ) THEN
        ALTER TABLE produtos
            ADD CONSTRAINT fk_produtos_categorias_id_categoria
            FOREIGN KEY (id_categoria)
            REFERENCES categorias (id_categoria)
            ON DELETE RESTRICT;
    END IF;
END $$;

COMMIT;